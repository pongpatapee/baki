#!/usr/bin/env node
/**
 * Builds the bundled exercise demonstration photos.
 *
 *   npm run images:exercises
 *
 * Source: free-exercise-db (https://github.com/yuhonas/free-exercise-db), public domain (Unlicense),
 * pinned to a commit so builds are reproducible. Each mapped exercise gets its two photos
 * (start / end position), resized and recompressed into assets/exercises/<exercise id>/{0,1}.jpg.
 * It then generates src/db/seed/exerciseImages.ts, the static require() table Metro needs.
 *
 * The mapping from Baki exercise ids to free-exercise-db ids lives in scripts/exercise-image-map.json
 * (null = no faithful photo exists). Downloads are cached in .cache/exercise-images/.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATASET_COMMIT = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
const RAW = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${DATASET_COMMIT}/exercises`;
const MAP_FILE = join(ROOT, 'scripts/exercise-image-map.json');
const OUT_DIR = join(ROOT, 'assets/exercises');
const CACHE_DIR = join(ROOT, '.cache/exercise-images');
const TS_FILE = join(ROOT, 'src/db/seed/exerciseImages.ts');

const WIDTH = 480; // px; displayed at most ~full screen width on the detail page
const QUALITY = 70;
const FRAMES = [0, 1];

async function fetchCached(fedbId, frame) {
  const cached = join(CACHE_DIR, fedbId, `${frame}.jpg`);
  if (existsSync(cached)) return readFileSync(cached);
  const res = await fetch(`${RAW}/${encodeURIComponent(fedbId)}/${frame}.jpg`);
  if (!res.ok) throw new Error(`${fedbId}/${frame}.jpg: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  mkdirSync(dirname(cached), { recursive: true });
  writeFileSync(cached, buf);
  return buf;
}

async function main() {
  /** @type {Record<string, string | null>} */
  const map = JSON.parse(readFileSync(MAP_FILE, 'utf8'));
  const entries = Object.entries(map)
    .filter(([, fedbId]) => fedbId)
    .sort(([a], [b]) => a.localeCompare(b));

  rmSync(OUT_DIR, { recursive: true, force: true });
  const lines = [];
  let bytes = 0;
  const queue = [...entries];
  const worker = async () => {
    for (let next = queue.shift(); next; next = queue.shift()) {
      const [exId, fedbId] = next;
      for (const frame of FRAMES) {
        const input = await fetchCached(fedbId, frame);
        const out = await sharp(input)
          .resize({ width: WIDTH, withoutEnlargement: true })
          .jpeg({ quality: QUALITY, mozjpeg: true })
          .toBuffer();
        mkdirSync(join(OUT_DIR, exId), { recursive: true });
        writeFileSync(join(OUT_DIR, exId, `${frame}.jpg`), out);
        bytes += out.length;
      }
    }
  };
  await Promise.all(Array.from({ length: 8 }, worker));

  for (const [exId] of entries) {
    const reqs = FRAMES.map((f) => `require('../../../assets/exercises/${exId}/${f}.jpg')`).join(', ');
    lines.push(`  ${exId}: [${reqs}],`);
  }

  writeFileSync(
    TS_FILE,
    `// GENERATED by scripts/build-exercise-images.mjs — do not edit by hand.
// Photos: free-exercise-db (https://github.com/yuhonas/free-exercise-db), public domain (Unlicense).
/** Start / end position photos (Metro asset ids from require()) for seeded exercises, keyed by exercise id. */
export const EXERCISE_IMAGES: Readonly<Record<string, readonly [number, number]>> = {
${lines.join('\n')}
};
`,
  );
  console.log(`${entries.length} exercises, ${entries.length * FRAMES.length} images, ${(bytes / 1024 / 1024).toFixed(1)} MB`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
